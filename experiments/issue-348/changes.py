#!/usr/bin/env python3
"""Compare two inventories written by inventory.py, ecosystem by ecosystem.

Usage: python3 experiments/issue-348/changes.py DATA_DIR

Reads DATA_DIR/before/direct.json and DATA_DIR/after/direct.json and writes
DATA_DIR/changes.md: one row per active or archived declaration, with the
version before, after, and on the registry. dev/log snapshots are skipped.
"""

import json
import sys
from pathlib import Path


def load(path):
    return {
        (d["ecosystem"], d["path"], d["name"]): d
        for d in json.loads(path.read_text())
        if d["scope"] != "snapshot"
    }


def main(data):
    before = load(data / "before/direct.json")
    after = load(data / "after/direct.json")
    lines = [
        "# Declared versions before and after (active and archived manifests)",
        "",
        "Generated by `experiments/issue-348/changes.py` from `before/direct.json`",
        "and `after/direct.json` (both produced by `experiments/issue-348/inventory.py`).",
        "`dev/log` snapshots are left out; they keep their historical versions on purpose.",
    ]
    for ecosystem in sorted({key[0] for key in before.keys() | after.keys()}):
        lines += [
            "",
            f"## {ecosystem}",
            "",
            "| Scope | Manifest | Dependency | Before | After | Latest | Current |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
        keys = sorted(k for k in before.keys() | after.keys() if k[0] == ecosystem)
        # Stale rows first, then by scope, manifest and name.
        keys.sort(key=lambda k: (k in after and after[k]["current"], k[1:]))
        for key in keys:
            old, new = before.get(key), after.get(key)
            row = new or old
            current = (
                "yes" if new and new["current"] else "removed" if not new else "**no**"
            )
            lines.append(
                f"| {row['scope']} | `{key[1]}` | `{key[2]}` "
                f"| `{old['declared'] if old else '(added)'}` "
                f"| `{new['declared'] if new else '(removed)'}` "
                f"| `{row['latest']}` | {current} |"
            )
    (data / "changes.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
