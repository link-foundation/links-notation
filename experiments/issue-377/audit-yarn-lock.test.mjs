// node --test experiments/issue-377/audit-yarn-lock.test.mjs
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { lockedVersions, findings } from '../../scripts/ci/audit-yarn-lock.mjs';

const LOCK = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@isaacs/cliui@^8.0.2":
  version "8.0.2"
  resolved "https://registry.yarnpkg.com/@isaacs/cliui/-/cliui-8.0.2.tgz"

diff@^7.0.0:
  version "7.0.0"

minimatch@^9.0.4, minimatch@^9.0.5:
  version "9.0.9"
  dependencies:
    brace-expansion "^2.0.1"

minimatch@^5.1.6:
  version "5.1.6"
`;

test('every locked name keeps each version once, scoped names included', () => {
  assert.deepEqual(lockedVersions(LOCK), {
    '@isaacs/cliui': ['8.0.2'],
    diff: ['7.0.0'],
    minimatch: ['9.0.9', '5.1.6'],
  });
});

test('a dependency line is not mistaken for a locked version', () => {
  assert.equal(lockedVersions(LOCK)['brace-expansion'], undefined);
});

test('advisories below the audit level are left out', () => {
  const advisories = {
    diff: [{ severity: 'low', vulnerable_versions: '>=6.0.0 <8.0.3', url: 'https://github.com/advisories/GHSA-73rr-hh4g-fpgx' }],
    minimatch: [{ severity: 'moderate', vulnerable_versions: '<11.0.1', url: 'https://github.com/advisories/GHSA-g3hv-75wg-m249' }],
  };
  assert.deepEqual(findings(advisories, lockedVersions(LOCK), 'moderate'), [
    'minimatch 9.0.9, 5.1.6: moderate <11.0.1 https://github.com/advisories/GHSA-g3hv-75wg-m249',
  ]);
  assert.equal(findings(advisories, lockedVersions(LOCK), 'low').length, 2);
  assert.deepEqual(findings({}, lockedVersions(LOCK), 'low'), []);
});
