/**
 * Writes `build/generated/commonTest/ParityCases.kt`: the shared fixtures of
 * the repository as Kotlin values, so every target, browsers and devices
 * included, runs them without reading a file.
 *
 * - `PARITY_CASES`: `parity/text-fixtures.json`, the shared text corpus;
 * - `SYNTAX_CASES`: `parity/syntax-fixtures.json`, the shared syntax corpus;
 * - `NESTED_VECTOR_LINES`: `parity/nested-vectors.tsv`, the nested writer corpus;
 * - `BINARY_VECTOR_LINES`: `docs/protocol/binary-links-notation-vectors.txt`;
 * - `REFERENCE_LITERAL_LINES` and `INVALID_REFERENCE_LITERAL_LINES`:
 *   `docs/protocol/reference-literals.txt` and
 *   `docs/protocol/invalid-reference-literals.txt`.
 */
abstract class GenerateParityCases : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val parityCorpus: RegularFileProperty

    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val syntaxCorpus: RegularFileProperty

    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val nestedVectors: RegularFileProperty

    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val binaryVectors: RegularFileProperty

    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val referenceLiterals: RegularFileProperty

    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val invalidReferenceLiterals: RegularFileProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val out = StringBuilder()
        out.append("// Generated by the generateParityCases task of build.gradle.kts. Do not edit.\n")
        out.append("package io.github.linkfoundation.linksnotation\n\n")
        out.append("internal val PARITY_CASES: List<Case> = listOf(\n")
        appendCases(out, parityCorpus.get().asFile)
        out.append(")\n\n")
        out.append("internal val SYNTAX_CASES: List<SyntaxCase> = listOf(\n")
        appendSyntaxCases(out, syntaxCorpus.get().asFile)
        out.append(")\n\n")
        appendLines(out, "NESTED_VECTOR_LINES", nestedVectors.get().asFile)
        appendLines(out, "BINARY_VECTOR_LINES", binaryVectors.get().asFile)
        appendLines(out, "REFERENCE_LITERAL_LINES", referenceLiterals.get().asFile)
        appendLines(out, "INVALID_REFERENCE_LITERAL_LINES", invalidReferenceLiterals.get().asFile)
        val target = outputDir.get().file("ParityCases.kt").asFile
        target.parentFile.mkdirs()
        target.writeText(out.toString())
    }

    private fun appendCases(
        out: StringBuilder,
        file: java.io.File,
    ) {
        @Suppress("UNCHECKED_CAST")
        val cases = JsonSlurper().parse(file, "UTF-8") as List<Map<String, Any?>>
        for (case in cases) {
            out.append("    Case(\n")
            out.append("        id = ").append(literal(case["id"] as String)).append(",\n")
            out.append("        input = ").append(literal(case["input"] as String)).append(",\n")
            val expected = case["expected"] as List<*>?
            out
                .append("        expected = ")
                .append(if (expected == null) "null" else links(expected))
                .append(",\n")
            val format = case["format"] as String?
            out.append("        format = ").append(if (format == null) "null" else literal(format)).append(",\n")
            val lessParentheses = case["lessParentheses"] as String?
            out
                .append("        lessParentheses = ")
                .append(if (lessParentheses == null) "null" else literal(lessParentheses))
                .append(",\n")
            out.append("        error = ").append(case["error"] == true).append(",\n")
            val code = case["code"] as String?
            out.append("        code = ").append(if (code == null) "null" else literal(code)).append(",\n")
            out.append("        line = ").append((case["line"] as Number?)?.toInt() ?: 0).append(",\n")
            out.append("        column = ").append((case["column"] as Number?)?.toInt() ?: 0).append(",\n")
            val message = case["message"] as String?
            out.append("        message = ").append(if (message == null) "null" else literal(message)).append(",\n")
            out.append("    ),\n")
        }
    }

    private fun appendSyntaxCases(
        out: StringBuilder,
        file: java.io.File,
    ) {
        @Suppress("UNCHECKED_CAST")
        val cases = JsonSlurper().parse(file, "UTF-8") as List<Map<String, Any?>>
        for (case in cases) {
            out.append("    SyntaxCase(\n")
            out.append("        id = ").append(literal(case["id"] as String)).append(",\n")
            out.append("        input = ").append(literal(case["input"] as String)).append(",\n")
            out.append("        links = ").append(syntaxLinks(case["links"] as List<*>)).append(",\n")
            out.append("        cst = ").append(literal(case["cst"] as String)).append(",\n")
            out.append("    ),\n")
        }
    }

    private fun appendLines(
        out: StringBuilder,
        name: String,
        file: java.io.File,
    ) {
        out.append("internal val ").append(name).append(": List<String> = listOf(\n")
        for (line in file.readLines(Charsets.UTF_8)) {
            out.append("    ").append(literal(line)).append(",\n")
        }
        out.append(")\n\n")
    }

    private fun nullable(text: Any?): String = if (text == null) "null" else literal(text as String)

    private fun links(list: List<*>): String =
        list.joinToString(", ", "listOf(", ")") { item ->
            @Suppress("UNCHECKED_CAST")
            val link = item as Map<String, Any?>
            "Link(${nullable(link["id"])}, ${links(link["values"] as List<*>)})"
        }

    private fun syntaxLinks(list: List<*>): String =
        list.joinToString(", ", "listOf(", ")") { item ->
            @Suppress("UNCHECKED_CAST")
            val link = item as Map<String, Any?>
            "SyntaxLink(${nullable(link["id"])}, ${nullable(link["raw"])}, ${nullable(link["quote"])}, " +
                "${syntaxLinks(link["values"] as List<*>)})"
        }

    /** A Kotlin string literal that holds [text] exactly, every non-ASCII unit escaped. */
    private fun literal(text: String): String {
        val out = StringBuilder("\"")
        for (character in text) {
            when {
                character == '\\' -> out.append("\\\\")
                character == '"' -> out.append("\\\"")
                character == '$' -> out.append("\\$")
                character.code in 0x20..0x7e -> out.append(character)
                else -> out.append("\\u").append(String.format("%04x", character.code))
            }
        }
        return out.append('"').toString()
    }
}

